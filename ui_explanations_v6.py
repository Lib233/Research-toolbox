def column_detail(filename, column):
    """Return (中文名, 详细说明) and never silently invent unknown field science."""
    name=str(column); base=Path(filename).name
    if name in FILE_COLUMNS.get(base,{}):return FILE_COLUMNS[base][name]
    if name in COLUMN_HELP:return COLUMN_HELP[name]
    if name.endswith('_mean') and name[:-5] in COLUMN_HELP:
        ch,meaning=COLUMN_HELP[name[:-5]];return ch+'的均值','按照对应汇总表的统计单位计算均值。'+meaning
    if name.endswith('_std') and name[:-4] in COLUMN_HELP:
        ch,_=COLUMN_HELP[name[:-4]];return ch+'的标准差','描述汇总单位间的波动，若独立试样 n<2 不可可靠估计。'
    if name.endswith('_count') and name[:-6] in COLUMN_HELP:return '参与'+name[:-6]+'汇总的记录数','请核对这里数的是试样还是循环，不可自动当作独立样本 n。'
    for prefix in ('predicted_','uncertainty_sd_','gp_nominal_sd_','cv_abs_error_q90_','cv_predicted_','cv_residual_','cv_nominal_sd_','measured_','ci95_low_','ci95_high_','heuristic_low_','heuristic_high_'):
        if name.startswith(prefix):
            base_name=name[len(prefix):]
            title={'predicted_':'预测','uncertainty_sd_':'校正后预测标准差','gp_nominal_sd_':'未经误差修正的GP预测标准差','cv_abs_error_q90_':'留组绝对预测误差90%分位','cv_predicted_':'留组预测结果','cv_residual_':'留组预测残差（实测减预测）','cv_nominal_sd_':'留组GP原始标准差','measured_':'真实观测值','ci95_low_':'预测95%区间下限','ci95_high_':'预测95%区间上限','heuristic_low_':'经验误差下界（非统计置信区间）','heuristic_high_':'经验误差上界（非统计置信区间）'}[prefix]
            return title+'：'+base_name, '该值来自模型对响应 '+base_name+' 的推断，单位应与原始响应一致；不是实测结果。尤其预测区间不保证真实覆盖率。'
    if name.startswith('peak_') and name.endswith('_mean'):return '峰值的平均','请核对是在每轮还是每独立试样层级平均。'
    if name.endswith('_p') or name.endswith('_p_value'):return name+' 的 p 值','特定统计检验下的 p 值；不能解释为科学结论成立的概率，必须了解该检验假设。'
    if name.endswith('_N') or name.endswith('_mm') or name.endswith('_mJ') or name.endswith('_s'):
        unit=name.rsplit('_',1)[-1]
        return name+'（'+unit+'）','此为带单位的数值字段；准确测量定义与公式需结合生成它的模块、源代码和实验记录核实。'
    return '未收录字段（'+name+'）','此列目前没有经过核实的专用中文定义；保留原始列名便于与源文件核对，不能仅凭名称推断物理意义。'

def write_column_dictionary(folder, module=None):
    """Record meanings for every actually exported CSV header; never modify original CSV."""
    path=Path(folder)
    records=[]
    for csv in sorted(path.glob('*.csv')):
        if csv.name=='结果字段中文释义.csv':continue
        try:
            cols=pd.read_csv(csv,encoding='utf-8-sig',nrows=0).columns
        except (ValueError,UnicodeError,ImportError):continue
        for raw in cols:
            name=str(raw)
            known=(name in FILE_COLUMNS.get(csv.name,{}) or name in COLUMN_HELP or
                   any(name.endswith(suffix) and name[:-len(suffix)] in COLUMN_HELP
                       for suffix in ('_mean','_std')))
            if not known:continue
            zh,desc=column_detail(csv.name,raw)
            if zh.startswith('未收录字段（'):continue
            desc=desc.split('。',1)[0].strip()+'。' if '。' in desc else desc
            records.append({'结果文件':csv.name,'英文列名':name,'中文名称':zh,'详细解释及注意事项':desc})
    if not records:return None
    target=path/'结果字段中文释义.csv'
    pd.DataFrame(records).to_csv(target,index=False,encoding='utf-8-sig')
    summary=['# 本次分析结果：逐字段中文解释','',f'模块：{display_name(module) if module else "未指定"}','',
             '按结果文件列出已定义字段的名称和用途。','',
             '可直接打开 analysis_tables.xlsx 的“结果字段中文释义”工作表，或使用 CSV 查询。','']
    for r in records:
        summary.append(f'- **{r["结果文件"]} / {r["英文列名"]} — {r["中文名称"]}**：{r["详细解释及注意事项"]}')
    (path/'结果字段逐列说明.md').write_text('\n'.join(summary)+'\n',encoding='utf-8')
    return target


                                                                           
