def help_text(module, key, label, kind, choices):
    """Return literal help aligned to the CURRENT widget; always show real options."""
    explanation=MODULE_KEY_HELP.get((module,key), HELP.get(key,''))
    if not explanation:
        explanation=f'【用途】{label}。本框属于“{module}”模块。填写与本次真实数据一致的内容；若未确认含义，不要沿用演示默认值。'
    if key in {'pipeline_integrated_response','pipeline_integrated_reference','pipeline_integrated_targets','behavior_body','behavior_feet','behavior_substrate','pair_point_a','pair_point_b','motion_pairs'}:
        explanation+='\n\n这里必须使用源文件实际存在的列名或点名；演示名称只是填写格式示例。'
    if kind.startswith('choice:'):
        opts='\n'.join('  • '+str(shown) for raw,shown in choices)
        explanation+='\n\n可选设置：\n'+opts+'\n请从下拉框选择；选项名称不会改变源数据。'
    if kind=='checkbox':explanation+='\n\n【填写方式】勾选表示启用，不勾选就是不启用。'
    if kind=='multi':explanation+='\n\n【填写方式】这是多行文本框，需要多个设置时按提示逐行填写。'
    return explanation

                                                                           
                                                                            
