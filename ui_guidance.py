def field_text(module,key,label,kind='',current='',raw_value=''):
    detail=field_help(module,key)
    if detail is None:raise KeyError(f'缺少字段说明：{module}/{key}')
    definition,example,caution=detail
    msg=('这个位置是什么？\n'+definition+'\n\n怎么填写？\n'+example+'\n\n需要小心什么？\n'+caution)
    if kind.startswith('choice:'):
        options=kind.partition(':')[2].split('|')
        if raw_value and option_help(key,raw_value):
            msg+='\n\n【你当前选中】'+str(current)+'\n'+option_help(key,raw_value)
        msg+='\n\n各个选项到底有什么区别？'
        for raw in options:
            desc=option_help(key,raw)
            if desc:msg+='\n• '+raw+'：'+desc
            else:msg+='\n• '+raw+'：请根据数据类型和实验目的选择。'
    return msg

